import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { fileURLToPath, pathToFileURL } from "node:url";

const projectRoot = fileURLToPath(new URL("../", import.meta.url));
const outputs = ["pageDefinitionV2.ts", "pageDefinitionV2Schema.ts"];
const allocationMarker = "CONTRACT_TEST_TEMP=";

async function withFixture(run: (root: string) => Promise<void>) {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "contract-generation-test-"));
  try {
    await fs.mkdir(path.join(root, "scripts"));
    await fs.mkdir(path.join(root, "contracts"));
    await fs.copyFile(
      path.join(projectRoot, "scripts/generate-page-contract.mjs"),
      path.join(root, "scripts/generate-page-contract.mjs"),
    );
    // Only dependency resolution is shared; all inputs and writable outputs are isolated.
    await fs.symlink(
      path.join(projectRoot, "node_modules"),
      path.join(root, "node_modules"),
      "junction",
    );
    await fs.writeFile(
      path.join(root, "contracts/page-definition-v2.schema.json"),
      JSON.stringify({
        title: "FixturePage",
        type: "object",
        properties: { title: { type: "string" } },
      }),
    );
    // Observe actual allocation without replacing it. The failure is injected only after allocation.
    await fs.writeFile(
      path.join(root, "observe-temp.mjs"),
      `import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
// Windows may supply defaults at process startup; clear them in the child too.
for (const key of Object.keys(process.env)) {
  if (["TEMP", "TMP", "TMPDIR"].includes(key.toUpperCase())) delete process.env[key];
}
const mkdtemp = fs.mkdtemp.bind(fs);
fs.mkdtemp = async (...args) => {
  const directory = await mkdtemp(...args);
  console.log(${JSON.stringify(allocationMarker)} + JSON.stringify({ directory: path.resolve(directory), systemTemp: path.resolve(os.tmpdir()) }));
  if (process.env.CONTRACT_TEST_FAIL_WRITE === "1") {
    const writeFile = fs.writeFile.bind(fs);
    fs.writeFile = async (file, ...rest) => {
      if (path.dirname(path.resolve(file)) === path.resolve(directory)) throw new Error("Injected temporary write failure");
      return writeFile(file, ...rest);
    };
  }
  return directory;
};
`,
    );
    const generated = invoke(root, false);
    assert.equal(generated.status, 0, generated.stderr);
    // Old timestamps expose rewrites even when the generated bytes would be identical.
    for (const output of outputs) {
      await fs.utimes(outputPath(root, output), new Date("2001-01-01"), new Date("2001-01-01"));
    }
    await run(root);
  } finally {
    await fs.rm(root, { recursive: true, force: true });
  }
}

function outputPath(root: string, output: string) {
  return path.join(root, "src/types/generated", output);
}

function invoke(root: string, check = true, failWrite = false) {
  const env = { ...process.env };
  // Remove every casing: Windows environment variable names are case insensitive.
  for (const key of Object.keys(env)) {
    if (["TEMP", "TMP", "TMPDIR", "NODE_OPTIONS"].includes(key.toUpperCase())) delete env[key];
  }
  env.CONTRACT_TEST_FAIL_WRITE = failWrite ? "1" : "0";
  const result = spawnSync(
    process.execPath,
    [
      "--import",
      pathToFileURL(path.join(root, "observe-temp.mjs")).href,
      path.join(root, "scripts/generate-page-contract.mjs"),
      ...(check ? ["--check"] : []),
    ],
    { cwd: root, env, encoding: "utf8", timeout: 30_000 },
  );
  assert.ifError(result.error);
  assert.equal(result.signal, null, result.stderr);
  return result;
}

async function snapshot(root: string) {
  return Promise.all(
    outputs.map(async (output) => {
      const file = outputPath(root, output);
      try {
        return {
          output,
          bytes: await fs.readFile(file),
          mtimeNs: (await fs.stat(file, { bigint: true })).mtimeNs,
        };
      } catch (error) {
        if ((error as NodeJS.ErrnoException).code === "ENOENT") return { output, missing: true };
        throw error;
      }
    }),
  );
}

async function assertTempCleaned(stdout: string) {
  const records = stdout.split(/\r?\n/).filter((line) => line.startsWith(allocationMarker));
  assert.equal(records.length, 1, stdout);
  const record = JSON.parse(records[0].slice(allocationMarker.length)) as {
    directory: string;
    systemTemp: string;
  };
  assert.equal(
    path.dirname(record.directory),
    record.systemTemp,
    "check must allocate in os.tmpdir(), not the fixture/workspace cwd",
  );
  await assert.rejects(fs.stat(record.directory), { code: "ENOENT" });
}

test("contract check uses the OS temp directory without temp environment variables and leaves outputs untouched", async () => {
  await withFixture(async (root) => {
    const before = await snapshot(root);
    const result = invoke(root);
    assert.equal(result.status, 0, result.stderr);
    assert.match(result.stdout, /Verified generated TypeScript types and schema module/);
    assert.deepEqual(await snapshot(root), before);
    await assertTempCleaned(result.stdout);
  });
});

for (const output of outputs) {
  test(`contract check rejects stale ${output} without rewriting bytes or mtime`, async () => {
    await withFixture(async (root) => {
      await fs.appendFile(outputPath(root, output), "\n// deliberately stale\n");
      const before = await snapshot(root);
      const result = invoke(root);
      assert.equal(result.status, 1, result.stderr);
      assert.match(result.stderr, /Generated contract is stale:/);
      assert.ok(result.stderr.includes(output));
      assert.deepEqual(await snapshot(root), before);
      await assertTempCleaned(result.stdout);
    });
  });

  test(`contract check rejects missing ${output} without recreating it or touching its sibling`, async () => {
    await withFixture(async (root) => {
      await fs.unlink(outputPath(root, output));
      const before = await snapshot(root);
      const result = invoke(root);
      assert.equal(result.status, 1, result.stderr);
      assert.match(result.stderr, /Missing generated file:/);
      assert.ok(result.stderr.includes(output));
      assert.deepEqual(await snapshot(root), before);
      await assertTempCleaned(result.stdout);
    });
  });
}

test("repository generated contract outputs stay in sync with the authoritative schema", () => {
  const env = { ...process.env };
  for (const key of Object.keys(env)) {
    if (key.toUpperCase() === "NODE_OPTIONS") delete env[key];
  }
  const result = spawnSync(
    process.execPath,
    [path.join(projectRoot, "scripts/generate-page-contract.mjs"), "--check"],
    { cwd: projectRoot, env, encoding: "utf8", timeout: 30_000 },
  );
  assert.ifError(result.error);
  assert.equal(result.status, 0, `${result.stdout}\n${result.stderr}`);
  assert.match(result.stdout, /Verified generated TypeScript types and schema module/);
});

test("contract check cleans its temporary directory after an unexpected write failure", async () => {
  await withFixture(async (root) => {
    const before = await snapshot(root);
    const result = invoke(root, true, true);
    assert.equal(result.status, 1, result.stderr);
    assert.match(result.stderr, /Injected temporary write failure/);
    assert.deepEqual(await snapshot(root), before);
    await assertTempCleaned(result.stdout);
  });
});
